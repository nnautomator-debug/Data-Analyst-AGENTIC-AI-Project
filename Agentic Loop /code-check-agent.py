def _truncate(text: str, limit: int) -> str:
    value = str(text or "").strip()
    if len(value) <= limit:
        return value
    return value[:limit] + "\n...[truncated]"


def _module_name(node: ast.AST) -> str:
    if isinstance(node, ast.Import):
        return node.names[0].name.split(".")[0] if node.names else ""
    if isinstance(node, ast.ImportFrom):
        return (node.module or "").split(".")[0]
    return ""


def _static_checks(code: str) -> list[str]:
    issues: list[str] = []

    try:
        compile(code, "<exec-agent-code>", "exec")
    except SyntaxError as exc:
        location = exc.lineno or 0
        detail = (exc.text or "").strip()
        issues.append(f"line {location}: syntax error: {exc.msg}: {detail}")

    try:
        tree = ast.parse(code)
    except SyntaxError:
        tree = None

    if tree is not None:
        seen_imports: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                module = _module_name(node)
                if module and module not in seen_imports:
                    seen_imports.add(module)
                    if module not in ALLOWED_IMPORTS:
                        issues.append(
                            f"line {node.lineno}: tech-stack violation: "
                            f"disallowed import {module!r}"
                        )

    for pattern, label in BLOCKED_PATTERNS:
        match = pattern.search(code)
        if match:
            line_number = code[: match.start()].count("\n") + 1
            issues.append(
                f"line {line_number}: tech-stack violation: {label}: "
                f"{match.group(0)!r}"
            )

    return issues


def _clean_fixed_line(value: str) -> str:
    cleaned = str(value or "").strip()
    if not cleaned:
        return ""

    if cleaned.startswith("```"):
        lines = [line for line in cleaned.splitlines() if not line.strip().startswith("```")]
        cleaned = "\n".join(lines).strip()

    for line in cleaned.splitlines():
        candidate = line.strip()
        if candidate:
            return candidate
    return ""


def _clean_code_block(value: str) -> str:
    text = str(value or "").strip()
    if not text:
        return ""

    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].strip().startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip().startswith("```"):
            lines = lines[:-1]
        text = "\n".join(lines).strip()

    return text


def _limit_reasoning(value: str, max_words: int = 40) -> str:
    words = str(value or "").split()
    return " ".join(words[:max_words])


def _extract_json_string(text: str, key: str) -> str:
    match = re.search(rf'"{re.escape(key)}"\s*:\s*"', text)
    if not match:
        return ""

    decoder = json.JSONDecoder(strict=False)
    try:
        value, _ = decoder.raw_decode(text[match.end() - 1 :])
        return str(value)
    except json.JSONDecodeError:
        return ""


def _repair_json(text: str) -> str:
    pattern = re.compile(r'("(?:fixed_line|reason|cause)"\s*:\s*")(.*?)("\s*[,}])', re.S)

    def escape_inner(match: re.Match) -> str:
        inner = re.sub(r'(?<!\\)"', r'\\"', match.group(2))
        return match.group(1) + inner + match.group(3)

    return pattern.sub(escape_inner, text)


def _parse_result(raw: str) -> CodeCheckResult:
    cleaned = str(raw or "").strip()
    candidates = [cleaned, _repair_json(cleaned)]

    json_match = re.search(r"\{.*\}", cleaned, re.S)
    if json_match:
        candidates.insert(0, json_match.group(0))
        candidates.append(_repair_json(json_match.group(0)))

    for candidate in candidates:
        payload = None
        for strict in (True, False):
            try:
                payload = json.loads(candidate, strict=strict)
                break
            except json.JSONDecodeError:
                continue

        if not isinstance(payload, dict):
            continue

        corrected_code = _clean_code_block(payload.get("code", ""))
        if corrected_code:
            reasoning = (
                payload.get("reasoning")
                or payload.get("cause")
                or "The checker corrected the code logic."
            )
            reasoning = _limit_reasoning(str(reasoning))
            return CodeCheckResult(
                verdict="FAIL",
                cause=reasoning,
                fixes=[],
                corrected_code=corrected_code,
                reasoning=reasoning,
            )

        verdict = str(payload.get("verdict", "")).strip().upper()
        if verdict not in {"PASS", "FAIL"}:
            continue

        cause = str(payload.get("cause", "")).strip()

        if verdict == "PASS":
            return CodeCheckResult(verdict="PASS", cause="", fixes=[])

        fixes: list[CodeFix] = []
        raw_fixes = payload.get("fixes")
        if isinstance(raw_fixes, list):
            for item in raw_fixes:
                if not isinstance(item, dict):
                    continue
                line_match = re.search(
                    r"\d+",
                    str(item.get("line_number", item.get("line", 0))),
                )
                line_number = int(line_match.group()) if line_match else 0
                fixes.append(
                    CodeFix(
                        line_number=max(0, line_number),
                        fixed_line=_clean_fixed_line(item.get("fixed_line", "")),
                        reason=str(item.get("reason", "")).strip(),
                    )
                )

        if not fixes and payload.get("fixed_line"):
            try:
                line_number = int(payload.get("line_number", 0))
            except (TypeError, ValueError):
                line_number = 0
            fixes.append(
                CodeFix(
                    line_number=max(0, line_number),
                    fixed_line=_clean_fixed_line(payload.get("fixed_line", "")),
                    reason=cause,
                )
            )

        return CodeCheckResult(
            verdict="FAIL",
            cause=cause or "The checker rejected the code.",
            fixes=fixes,
        )

    corrected_code = _clean_code_block(_extract_json_string(cleaned, "code"))
    if corrected_code:
        reasoning = _extract_json_string(cleaned, "reasoning")
        reasoning = _limit_reasoning(reasoning or "The checker corrected the code logic.")
        return CodeCheckResult(
            verdict="FAIL",
            cause=reasoning,
            fixes=[],
            corrected_code=corrected_code,
            reasoning=reasoning,
        )

    raise RuntimeError(f"Code Check Agent returned an unparseable response: {cleaned[:500]}")


def _get_llm() -> ChatOpenAI:
    api_key = os.getenv("NVIDIA_API_KEY") or os.getenv("NVIDA_API_KEY")
    if not api_key:
        raise RuntimeError("NVIDIA_API_KEY is missing from the environment.")

    return ChatOpenAI(
        model=os.getenv("CODE_CHECK_MODEL", DEFAULT_NVIDIA_MODEL),
        base_url=os.getenv("NVIDIA_BASE_URL", NVIDIA_BASE_URL),
        api_key=api_key,
        temperature=0,
        timeout=120,
        max_retries=2,
    )


def _run_llm(
    code: str,
    sandbox_error: str,
    stdout: str,
    stderr: str,
    user_query: str,
    dataset_profile: str,
    plan: list[dict],
    static_issues: list[str],
) -> CodeCheckResult:
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", CHECKER_SYSTEM_PROMPT),
            ("human", CHECKER_USER_PROMPT),
        ]
    )
    messages = prompt.format_messages(
        user_query=user_query or "No user request was provided.",
        plan=json.dumps(plan or [], indent=2, default=str),
        dataset_profile=_truncate(dataset_profile, MAX_PROFILE_CHARS),
        code=_truncate(code, MAX_OUTPUT_CHARS),
        sandbox_error=_truncate(sandbox_error, MAX_OUTPUT_CHARS),
        stdout=_truncate(stdout, MAX_OUTPUT_CHARS),
        stderr=_truncate(stderr, MAX_OUTPUT_CHARS),
        static_issues=json.dumps(static_issues, indent=2),
    )
    response = _get_llm().invoke(messages)
    content = response.content
    if isinstance(content, list):
        content = "\n".join(
            str(part.get("text", "")) if isinstance(part, dict) else str(part)
            for part in content
        )
    return _parse_result(str(content))


def _source_line(code: str, line_number: int) -> str:
    lines = code.splitlines()
    if 1 <= line_number <= len(lines):
        return lines[line_number - 1].strip()
    return ""


def _same_line(left: str, right: str) -> bool:
    return re.sub(r"\s+", "", left) == re.sub(r"\s+", "", right)


def _line_similarity(left: str, right: str) -> float:
    return difflib.SequenceMatcher(None, left.strip(), right.strip()).ratio()


def _align_fix_line_numbers(code: str, fixes: list[CodeFix]) -> list[CodeFix]:
    lines = code.splitlines()
    aligned: list[CodeFix] = []

    for fix in fixes:
        if not fix.fixed_line.strip():
            aligned.append(fix)
            continue

        best_line = 0
        best_score = 0.0
        for line_number, line in enumerate(lines, start=1):
            if not line.strip():
                continue
            score = _line_similarity(fix.fixed_line, line)
            if score > best_score:
                best_score = score
                best_line = line_number

        current_line = _source_line(code, fix.line_number)
        current_score = _line_similarity(fix.fixed_line, current_line) if current_line else 0.0

        if best_line and best_score >= 0.35 and best_score > current_score + 0.05:
            fix = fix.model_copy(update={"line_number": best_line})

        aligned.append(fix)

    return aligned


def _ensure_actionable_fix(code: str, fix: CodeFix) -> CodeFix | None:
    original = _source_line(code, fix.line_number)
    if not original or not fix.fixed_line or not _same_line(original, fix.fixed_line):
        return fix

    if ".dt" in original and "order_date" in original and "pd.to_datetime" not in original:
        fixed_line = re.sub(
            r"""df\[["']order_date["']\]""",
            'pd.to_datetime(df["order_date"], format="mixed", dayfirst=True, errors="coerce")',
            original,
        )
        if not _same_line(original, fixed_line):
            return CodeFix(
                line_number=fix.line_number,
                fixed_line=fixed_line,
                reason=fix.reason,
            )

    if "read_csv" in original and "thousands" not in original:
        fixed_line = re.sub(
            r"(read_csv\([^)]*)\)",
            r'\1, thousands=",")',
            original,
            count=1,
        )
        if not _same_line(original, fixed_line):
            return CodeFix(
                line_number=fix.line_number,
                fixed_line=fixed_line,
                reason=fix.reason,
            )

    return None


def _static_tech_fixes(static_issues: list[str]) -> list[CodeFix]:
    fixes: list[CodeFix] = []
    for issue in static_issues:
        if "tech-stack violation" not in issue:
            continue
        match = re.match(r"line (\d+): (.*)", issue)
        if not match:
            continue
        fixes.append(
            CodeFix(
                line_number=int(match.group(1)),
                fixed_line="",
                reason=match.group(2),
            )
        )
    return fixes


def _already_handled(code: str, fix: CodeFix) -> bool:
    text = f"{fix.reason} {fix.fixed_line}".lower()
    code_lower = code.lower()

    has_thousands = bool(re.search(r"""thousands\s*=\s*["']\s*,\s*["']""", code))
    numeric_terms = ("to_numeric", "str.replace", "comma", "numeric type", "numeric column")
    if has_thousands and any(term in text for term in numeric_terms):
        return True

    has_date_parse = bool(
        re.search(r"to_datetime\s*\([^)]*order_date", code)
        and 'format="mixed"' in code_lower
        and "dayfirst=true" in code_lower
    )
    if has_date_parse and ("order_date" in text or "datetime" in text or ".dt accessor" in text):
        return True

    if ("period" in text or "strftime" in text) and (
        "format" in text or "readable" in text or "print" in text
    ):
        return True

    return False


def _filter_handled_fixes(code: str, result: CodeCheckResult) -> CodeCheckResult:
    if not result.fixes:
        return result

    fixes = [fix for fix in result.fixes if not _already_handled(code, fix)]
    if len(fixes) == len(result.fixes):
        return result

    cause = "; ".join(fix.reason for fix in fixes if fix.reason) or result.cause
    if not fixes:
        cause = ""

    return CodeCheckResult(
        verdict="PASS" if not fixes else result.verdict,
        cause=cause,
        fixes=fixes,
    )


def check_code(
    code: str,
    sandbox_error: str = "",
    stdout: str = "",
    stderr: str = "",
    user_query: str = "",
    dataset_profile: str = "",
    plan: list[dict] | None = None,
) -> CodeCheckResult:
    if not str(code or "").strip():
        return CodeCheckResult(
            verdict="FAIL",
            cause="No code was provided to the Code Check Agent.",
            fixes=[],
        )

    static_issues = _static_checks(code)
    result = _run_llm(
        code=code,
        sandbox_error=sandbox_error,
        stdout=stdout,
        stderr=stderr,
        user_query=user_query,
        dataset_profile=dataset_profile,
        plan=plan or [],
        static_issues=static_issues,
    )

    if result.corrected_code:
        reasoning = _limit_reasoning(
            result.reasoning or result.cause or "The checker corrected the code logic."
        )
        return CodeCheckResult(
            verdict="FAIL",
            cause=reasoning,
            fixes=[],
            corrected_code=result.corrected_code,
            reasoning=reasoning,
        )

    fixes = _align_fix_line_numbers(code, result.fixes)
    actionable = [
        updated
        for fix in fixes
        if (updated := _ensure_actionable_fix(code, fix)) is not None
    ]
    fixes_by_line = {fix.line_number: fix for fix in actionable}
    for static_fix in _static_tech_fixes(static_issues):
        fixes_by_line[static_fix.line_number] = static_fix

    result = CodeCheckResult(
        verdict=result.verdict,
        cause=result.cause,
        fixes=sorted(fixes_by_line.values(), key=lambda fix: fix.line_number),
    )
    result = _filter_handled_fixes(code, result)

    if not result.fixes and not sandbox_error and not static_issues:
        result = CodeCheckResult(verdict="PASS", cause="", fixes=[])

    if sandbox_error:
        result = CodeCheckResult(
            verdict="FAIL",
            cause=result.cause or f"Sandbox execution failed: {sandbox_error.strip()}",
            fixes=result.fixes,
        )

    if static_issues:
        result = CodeCheckResult(
            verdict="FAIL",
            cause=result.cause or "; ".join(static_issues),
            fixes=result.fixes,
        )

    return result


def check_code_text(
    code: str,
    sandbox_error: str = "",
    stdout: str = "",
    stderr: str = "",
    user_query: str = "",
    dataset_profile: str = "",
    plan: list[dict] | None = None,
) -> str:
    result = check_code(
        code=code,
        sandbox_error=sandbox_error,
        stdout=stdout,
        stderr=stderr,
        user_query=user_query,
        dataset_profile=dataset_profile,
        plan=plan,
    )
    if result.verdict == "PASS":
        return "PASS"
    if result.corrected_code:
        return json.dumps(
            {
                "code": result.corrected_code,
                "reasoning": result.reasoning or result.cause,
            },
            indent=2,
        )
    return json.dumps(result.model_dump(), indent=2)


def code_check_node(state: CodeCheckState) -> dict:
    code = state.get("code", "")
    try:
        result = check_code(
            code=code,
            sandbox_error=state.get("sandbox_error", ""),
            stdout=state.get("stdout", ""),
            stderr=state.get("stderr", ""),
            user_query=state.get("user_query", ""),
            dataset_profile=state.get("dataset_profile", ""),
            plan=state.get("plan", []),
        )
        return {
            "verdict": result.verdict,
            "cause": result.cause,
            "fixes": [fix.model_dump() for fix in result.fixes],
            "corrected_code": result.corrected_code,
            "reasoning": result.reasoning,
            "code_check": result.model_dump(),
            "error": "",
        }
    except Exception as exc:
        return {
            "verdict": "FAIL",
            "cause": f"Code Check Agent failed: {exc}",
            "fixes": [],
            "corrected_code": "",
            "reasoning": "",
            "code_check": {},
            "error": f"Code Check Agent failed: {exc}",
        }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--code", default="")
    parser.add_argument("--code-file", default="")
    parser.add_argument("--error", default="")
    parser.add_argument("--stdout", default="")
    parser.add_argument("--stderr", default="")
    parser.add_argument("--query", default="")
    parser.add_argument("--profile-file", default="")
    args = parser.parse_args()

    code = args.code
    if args.code_file:
        code = Path(args.code_file).expanduser().read_text(encoding="utf-8")

    dataset_profile = ""
    if args.profile_file:
        dataset_profile = Path(args.profile_file).expanduser().read_text(encoding="utf-8")

    result = code_check_node(
        {
            "code": code,
            "sandbox_error": args.error,
            "stdout": args.stdout,
            "stderr": args.stderr,
            "user_query": args.query,
            "dataset_profile": dataset_profile,
            "plan": [],
        }
    )

    if result.get("verdict") == "PASS":
        print("PASS")
        return

    if result.get("corrected_code"):
        print(
            json.dumps(
                {
                    "code": result.get("corrected_code"),
                    "reasoning": result.get("reasoning") or result.get("cause"),
                },
                indent=2,
            )
        )
        return

    print(
        json.dumps(
            {
                "verdict": result.get("verdict"),
                "cause": result.get("cause"),
                "fixes": result.get("fixes"),
                "error": result.get("error"),
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()

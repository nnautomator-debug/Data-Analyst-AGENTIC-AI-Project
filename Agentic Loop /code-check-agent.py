BLOCKED_PATTERNS = [
    (re.compile(r"(?m)^\s*!(?!=)"), "IPython shell escape"),
    (
        re.compile(r"(?m)^\s*%%(?:bash|sh|shell|script)\b"),
        "IPython shell magic",
    ),
    (
        re.compile(r"(?m)^\s*%(?:system|sx|bash|sh|shell)\b"),
        "IPython system magic",
    ),
    (
        re.compile(r"\bos\.(?:system|popen|spawn\w*|exec\w*)\s*\("),
        "OS process execution",
    ),
    (re.compile(r"\bsubprocess\.\w+\s*\("), "subprocess execution"),
    (re.compile(r"\bpty\.spawn\s*\("), "pty execution"),
    (re.compile(r"\bshell\s*=\s*True\b"), "shell=True"),
    (
        re.compile(r"\b(?:bash|zsh|fish|powershell|cmd\.exe)\b"),
        "shell binary",
    ),
    (re.compile(r"\b(?:curl|wget)\b"), "network shell command"),
    (re.compile(r"\brm\s+-rf\b"), "destructive shell command"),
    (re.compile(r"\bsudo\b"), "privileged shell command"),
    (re.compile(r"\bshutil\.rmtree\s*\("), "destructive filesystem operation"),
    (
        re.compile(r"\b(?:requests|httpx|urllib|socket)\.\w+\s*\("),
        "network operation",
    ),
]


class CodeCheckState(TypedDict, total=False):
    code: str
    sandbox_error: str
    stdout: str
    stderr: str
    user_query: str
    dataset_profile: str
    plan: list[dict]
    attempt: int
    verdict: str
    cause: str
    fixes: list[dict]
    corrected_code: str
    reasoning: str
    code_check: dict
    error: str


class CodeFix(BaseModel):
    line_number: int = Field(ge=0)
    fixed_line: str = ""
    reason: str = ""


class CodeCheckResult(BaseModel):
    verdict: str = Field(pattern="^(PASS|FAIL)$")
    cause: str = ""
    fixes: list[CodeFix] = Field(default_factory=list)
    corrected_code: str = ""
    reasoning: str = ""


